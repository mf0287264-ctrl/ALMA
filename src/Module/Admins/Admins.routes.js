import express from 'express';
import controller from './Admins.controller.js';
import { validate } from '../../Middleware/validation.middleware.js';
import { authenticate, requireRole } from '../../Middleware/auth.middleware.js';
import { multerUpload } from '../../Middleware/multer.middleware.js';
import { uploadProfilePictureHandler, updateUserNameHandler } from '../Users/Users.controller.js';
import { createAdminSchema, updateAdminSchema, loginAdminSchema } from '../../Validation/Admin.validation.js';

const router = express.Router();
router.post('/login', validate(loginAdminSchema), controller.login);
router.use(authenticate, requireRole('admin'));
router.post('/', validate(createAdminSchema), controller.create);
router.post('/guardian-links', controller.linkGuardian);
router.post('/teacher-approvals', controller.verifyTeacher);
router.get('/profile', controller.getProfile);
router.get('/list', controller.getAll);
router.get('/', controller.getProfile);
router.patch('/name', updateUserNameHandler);
router.put('/name', updateUserNameHandler);
router.patch('/profile-picture', multerUpload({ desiredPath: 'Profiles' }).single('profile'), uploadProfilePictureHandler);
router.post('/profile-picture', multerUpload({ desiredPath: 'Profiles' }).single('profile'), uploadProfilePictureHandler);
router.put('/profile', validate(updateAdminSchema), controller.update);
router.put('/', validate(updateAdminSchema), controller.update);
router.get('/:id', controller.getById);
router.put('/:id', validate(updateAdminSchema), controller.update);
router.delete('/:id', controller.delete);
export default router;
